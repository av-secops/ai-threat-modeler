import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const api = process.env.AEGIS_TEST_API_URL || 'http://127.0.0.1:8011';
const output = path.resolve('backend/evaluation_reports/product-dashboard');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
await context.addInitScript(() => { if (!sessionStorage.getItem('aegis-workspace-token')) sessionStorage.setItem('aegis-workspace-token', 'dashboard-test-editor'); localStorage.setItem('theme', 'light'); });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(30000);
await page.route('**/enterprise/**', async route => {
  const url = new URL(route.request().url());
  const response = await route.fetch({ url: api + url.pathname + url.search });
  await route.fulfill({ response });
});
const ready = async () => {
  await page.getByRole('heading', { name: 'Security dashboard', exact: true }).waitFor();
  await page.getByText('Loading dashboard...', { exact: true }).waitFor({ state: 'hidden' });
  await page.getByRole('navigation', { name: 'Security dashboard views' }).getByRole('button', { name: /^Risks/ }).click();
  await page.getByRole('table', { name: 'Product risk register', exact: true }).waitFor();
};
const count = async () => Number((await page.getByRole('status').filter({ hasText: 'finding occurrences' }).innerText()).split(' ')[0]);
try {
  await page.goto(process.env.AEGIS_UI_URL || 'http://127.0.0.1:5173/');
  await page.getByRole('button', { name: 'Atlas Product', exact: true }).click();
  await page.getByRole('button', { name: 'Product security dashboard', exact: true }).click();
  await ready();
  assert.equal(await count(), 35);
  await page.getByRole('navigation', { name: 'Security dashboard views' }).getByRole('button', { name: 'Overview', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'desktop-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Critical: 9 open risks', exact: true }).click();
  await ready();
  assert.equal(await count(), 9);
  assert.match(page.url(), /severity=Critical/);
  await page.reload(); await ready();
  assert.equal(await count(), 9);
  await page.getByRole('button', { name: 'View details for Cross-tenant order access (0)', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByLabel('Product review status', { exact: true }).selectOption('action_required');
  await page.getByLabel('Product team remarks', { exact: true }).fill('Product architect confirms remediation work is required.');
  const saved = page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('/reviews/'));
  await page.getByRole('button', { name: 'Record review', exact: true }).click();
  assert.equal((await saved).status(), 200);
  await page.getByRole('button', { name: 'Close risk details', exact: true }).click();
  await ready();
  assert.ok((await page.getByRole('table', { name: 'Product risk register', exact: true }).innerText()).includes('Action required'));
  await page.getByRole('button', { name: 'Reset dashboard filters', exact: true }).click(); await ready();
  await page.getByRole('button', { name: 'View details for Cross-tenant order access (0)', exact: true }).click();
  await page.getByRole('button', { name: 'Open report revision', exact: true }).click();
  await page.getByRole('button', { name: 'Back to dashboard', exact: true }).waitFor();
  await page.goBack(); await ready();
  await page.getByRole('button', { name: 'Next product findings', exact: true }).click(); await ready();
  assert.equal(await page.getByRole('table', { name: 'Product risk register', exact: true }).locator('tbody tr').count(), 10);
  await page.getByRole('button', { name: 'Previous product findings', exact: true }).click(); await ready();
  await page.getByLabel('Search product findings', { exact: true }).fill('Cross-tenant'); await ready();
  assert.equal(await count(), 9);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export filtered risk register', exact: true }).click();
  const download = await downloadPromise;
  const csv = await readFile(await download.path(), 'utf8');
  assert.equal(csv.trim().split(/\r?\n/).length, 10);
  await page.getByRole('button', { name: 'Reset dashboard filters', exact: true }).click(); await ready();
  await page.getByRole('navigation', { name: 'Security dashboard views' }).getByRole('button', { name: 'History', exact: true }).click();
  await page.getByRole('button', { name: 'Record overview', exact: true }).click();
  await page.getByRole('table', { name: 'Dashboard observations', exact: true }).locator('tbody tr').first().waitFor();
  await page.getByTitle('Dark mode', { exact: true }).click();
  await page.screenshot({ path: path.join(output, 'desktop-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'mobile-dark-viewport.png') });
  await page.screenshot({ path: path.join(output, 'mobile-dark.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.getByTitle('Light mode', { exact: true }).click();
  await page.screenshot({ path: path.join(output, 'mobile-light.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Back to releases', exact: true }).click();
  await page.getByRole('table', { name: 'Product releases', exact: true }).waitFor();
  await page.goBack(); await ready();
  await page.getByRole('button', { name: 'Back to releases', exact: true }).click();
  await page.getByRole('main').getByRole('button', { name: 'Products', exact: true }).click();
  await page.getByRole('button', { name: 'Product security portfolio', exact: true }).click();
  await page.getByRole('heading', { name: 'Product security portfolio', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Dashboard for Atlas Product', exact: true }).click(); await ready();
  await page.evaluate(() => sessionStorage.setItem('aegis-workspace-token', 'dashboard-test-viewer'));
  await page.reload(); await ready();
  await page.getByRole('navigation', { name: 'Security dashboard views' }).getByRole('button', { name: 'History', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Record overview', exact: true }).count(), 0);
  await ready();
  await page.getByRole('button', { name: 'View details for Cross-tenant order access (0)', exact: true }).click();
  assert.equal(await page.getByLabel('Product review status', { exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Close risk details', exact: true }).click();
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, 'verification.json'), JSON.stringify({ passed: true, browserErrors: errors, checks: ['filters', 'reload', 'pagination', 'review_refresh', 'csv', 'history', 'themes', 'mobile', 'back', 'portfolio', 'viewer'] }, null, 2));
  console.log('Product dashboard browser checks passed. Screenshots:', output);
} finally {
  await browser.close();
}
